/* Estas cuatro funciones son las que en el proyecto viven en un componente
 * aparte (nebulaedge_i2c). Acá están incluidas para que el archivo se baste
 * solo. La velocidad por defecto del bus se guarda al inicializarlo, así que
 * un slave puede pedir freq_hz = 0 y heredarla. */

static uint32_t s_default_freq_hz = I2C_MASTER_FREQ_HZ;

static esp_err_t i2c_master_init(i2c_master_bus_handle_t *bus_handle) {
    i2c_master_bus_config_t bus_cfg = {
        .i2c_port = I2C_NUM_0,
        .sda_io_num = I2C_MASTER_SDA_IO,
        .scl_io_num = I2C_MASTER_SCL_IO,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };

    esp_err_t err = i2c_new_master_bus(&bus_cfg, bus_handle);
    vTaskDelay(pdMS_TO_TICKS(50));
    return err;
}

static esp_err_t i2c_slave_init(i2c_master_bus_handle_t *bus_handle,
                                i2c_master_dev_handle_t *device,
                                int slave_addr, uint32_t freq_hz) {
    if (bus_handle == NULL || *bus_handle == NULL || device == NULL) {
        return ESP_ERR_INVALID_ARG;
    }

    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = slave_addr,
        .scl_speed_hz = (freq_hz > 0) ? freq_hz : s_default_freq_hz,
    };

    esp_err_t err = i2c_master_bus_add_device(*bus_handle, &dev_cfg, device);
    vTaskDelay(pdMS_TO_TICKS(50));
    return err;
}

static esp_err_t i2c_slave_deinit(i2c_master_dev_handle_t *device) {
    if (device == NULL || *device == NULL) {
        return ESP_OK;
    }
    esp_err_t err = i2c_master_bus_rm_device(*device);
    if (err == ESP_OK) {
        *device = NULL;
    }
    return err;
}

/* Lee `size` bytes a partir del registro `data_address`.
 *
 * Son DOS transacciones: primero se escribe la dirección del registro, después
 * se leen los datos. En un sistema con varias tasks compartiendo el bus hay que
 * protegerlas con un mutex para que nadie se cuele entre las dos. */
static esp_err_t device_read(i2c_master_dev_handle_t device, uint8_t *data_address,
                             uint8_t *data_rd, size_t size, const char *tag) {
    if (device == NULL || data_address == NULL || data_rd == NULL) {
        ESP_LOGE(tag, "device_read con parámetros inválidos");
        return ESP_ERR_INVALID_ARG;
    }
    if (size == 0) {
        return ESP_OK;
    }

    esp_err_t err = i2c_master_transmit(device, data_address, 1, pdMS_TO_TICKS(2000));
    if (err != ESP_OK) {
        ESP_LOGE(tag, "Error al enviar dirección para lectura: %s", esp_err_to_name(err));
        return err;
    }

    err = i2c_master_receive(device, data_rd, size, pdMS_TO_TICKS(2000));
    if (err != ESP_OK) {
        ESP_LOGE(tag, "Error al recibir datos: %s", esp_err_to_name(err));
    }
    return err;
}

/* Escribe `size` bytes a partir del registro `data_address`. */
static esp_err_t device_write(i2c_master_dev_handle_t device, uint8_t *data_address,
                              uint8_t *data_wr, size_t size, const char *tag) {
    if (device == NULL || data_address == NULL || data_wr == NULL) {
        ESP_LOGE(tag, "device_write con parámetros inválidos");
        return ESP_ERR_INVALID_ARG;
    }

    uint8_t full_data[1 + size];
    full_data[0] = *data_address;
    memcpy(&full_data[1], data_wr, size);

    esp_err_t err = i2c_master_transmit(device, full_data, sizeof(full_data), pdMS_TO_TICKS(2000));
    if (err != ESP_OK) {
        ESP_LOGE(tag, "Error al escribir datos: %s", esp_err_to_name(err));
    }
    return err;
}


